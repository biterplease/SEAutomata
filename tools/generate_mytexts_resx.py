#!/usr/bin/env python3
"""Generates the mod's English Data/Localization/MyTexts.resx from the strings defined in
Automata/Data/Scripts/Automata/Util/Strings/*.cs.

Every string there is one line:

    public static readonly MyStringId Drone_EnableAI = MyStringId.GetOrCompute("{LOC:Drone_EnableAI}"); // "Enable AI"

The id inside the {LOC:...} tag in GetOrCompute() is the resx key (the game resolves mod strings only through {LOC:key} tags), the C# string literal in the trailing comment is its English text.
KeenStrings.cs is skipped (the game already defines those ids), as are lines without that comment (BLANK).
The whole file is regenerated on every run: edit the English text in the strings files, not in the resx.
Keys that are new to the resx are printed as `insert <line number in the new file>: <key>`, keys that are no
longer defined as `remove: <key>`.

    python tools/generate_mytexts_resx.py            write the file
    python tools/generate_mytexts_resx.py --check    exit 1 when the file is out of date (writes nothing)
"""
import os
import re
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STRINGS = os.path.join(ROOT, 'Automata', 'Data', 'Scripts', 'Automata', 'Util', 'Strings')
OUT = os.path.join(ROOT, 'Automata', 'Data', 'Localization', 'MyTexts.resx')

SKIP = 'KeenStrings.cs'   # the game's own ids: not ours to define
LINE = re.compile(r'^\s*public static readonly MyStringId (\w+) = MyStringId\.GetOrCompute\("\{LOC:(\w+)\}"\);\s*//\s*("(?:[^"\\]|\\.)*")\s*$')
MINIMAL_HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype">
    <value>text/microsoft-resx</value>
  </resheader>
  <resheader name="version">
    <value>2.0</value>
  </resheader>
  <resheader name="reader">
    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
  <resheader name="writer">
    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
'''


def decode(lit):
    """C# regular string literal -> text."""
    s = lit[1:-1]
    out = []
    i = 0
    simple = {'n': '\n', 't': '\t', 'r': '\r', '0': '\0', '\\': '\\', '"': '"', "'": "'"}
    while i < len(s):
        c = s[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        n = s[i + 1]
        if n in simple:
            out.append(simple[n])
            i += 2
        elif n == 'u':
            out.append(chr(int(s[i + 2:i + 6], 16)))
            i += 6
        else:
            raise ValueError('unsupported escape \\%s in %s' % (n, lit))
    return ''.join(out)


def collect():
    files = sorted(f for f in os.listdir(STRINGS) if f.endswith('.cs') and f != SKIP)
    files.sort(key=lambda f: (f != 'Strings.cs', f))   # Strings.cs (common) first
    entries = []
    seen = {}
    for f in files:
        with open(os.path.join(STRINGS, f), encoding='utf-8-sig') as fh:
            for n, line in enumerate(fh, 1):
                m = LINE.match(line)
                if not m:
                    continue
                symbol, key, lit = m.groups()
                if symbol != key:
                    print('warning: %s:%d symbol %s != key %s' % (f, n, symbol, key), file=sys.stderr)
                if key in seen:
                    sys.exit('error: duplicate key %s (%s:%d, first in %s)' % (key, f, n, seen[key]))
                seen[key] = '%s:%d' % (f, n)
                entries.append((key, decode(lit)))
    return entries


def header():
    if os.path.exists(OUT):
        with open(OUT, encoding='utf-8-sig', newline='') as fh:
            text = fh.read().replace('\r\n', '\n')
        end = text.rfind('</resheader>')
        if end >= 0:
            return text[:text.index('\n', end) + 1]
    return MINIMAL_HEADER


DATA = re.compile(r'^\s*<data name="([^"]*)"')


def render(entries):
    out = [header().rstrip('\n'),
           '  <!-- Generated by tools/generate_mytexts_resx.py from Automata/Data/Scripts/Automata/Util/Strings/*.cs. Do not edit: change the strings there. -->']
    for key, value in entries:
        out.append('  <data name="%s" xml:space="preserve">' % escape(key, {'"': '&quot;'}))
        out.append('    <value>%s</value>' % escape(value))
        out.append('  </data>')
    out.append('</root>')
    return '\r\n'.join(out) + '\r\n'


def keys_of(text):
    """{key: line number} of the <data> entries, outside XML comments (the header has a commented example)."""
    keys, in_comment = {}, False
    for n, line in enumerate(text.splitlines(), 1):
        was_comment = in_comment
        if '<!--' in line:
            in_comment = True
        if '-->' in line:
            in_comment = False
        m = None if was_comment or in_comment else DATA.match(line)
        if m:
            keys[m.group(1)] = n
    return keys


def main():
    entries = collect()
    text = render(entries)
    current = open(OUT, encoding='utf-8', newline='').read() if os.path.exists(OUT) else ''
    old = keys_of(current)
    for key, n in sorted(keys_of(text).items(), key=lambda kv: kv[1]):
        if key not in old:
            print('insert %d: %s' % (n, key))
    for key in sorted(set(old) - set(k for k, _ in entries)):
        print('remove: %s' % key)
    if '--check' in sys.argv:
        if current != text:
            print('MyTexts.resx is out of date: run python tools/generate_mytexts_resx.py')
            sys.exit(1)
        print('MyTexts.resx is up to date (%d strings)' % len(entries))
        return
    if current != text:
        with open(OUT, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
    print('%s %s (%d strings)' % ('wrote' if current != text else 'unchanged', os.path.relpath(OUT, ROOT), len(entries)))


if __name__ == '__main__':
    main()
